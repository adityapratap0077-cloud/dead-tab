#!/usr/bin/env python3
"""Wrap data/exhibits.json + data/categories.json into assets/js/data.js
so pages can load content with a plain <script> tag (no fetch, no server
needed, works on GitHub Pages and from a local folder alike).

Run after every content edit:
    python3 scripts/build_data_js.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load(name):
    with open(os.path.join(ROOT, "data", name), encoding="utf-8") as f:
        return json.load(f)

exhibits = load("exhibits.json")
categories = load("categories.json")

out = (
    "// Generated by scripts/build_data_js.py from data/*.json — do not edit by hand.\n"
    "window.DEADTAB_EXHIBITS = " + json.dumps(exhibits, ensure_ascii=False, indent=1) + ";\n"
    "window.DEADTAB_CATEGORIES = " + json.dumps(categories, ensure_ascii=False, indent=1) + ";\n"
)
dest = os.path.join(ROOT, "assets", "js", "data.js")
with open(dest, "w", encoding="utf-8") as f:
    f.write(out)
print(f"Wrote {dest} ({len(exhibits)} exhibits, {len(categories)} categories)")
